        assert.ok(!week.shopping.some((item: any) => item.id === removedId));
        assert.equal(week.menu.mealCount, 3);
        assert.equal(week.menuHistory.length, 2);
        const replacement = initialRecipes.find(recipe => recipe.category === 'main' && recipe.id !== recipes[0].id)!;
        result = await request(path + '/preview', 'POST', { revision: week.revision, recipes: [replacement, ...recipes.slice(1)] });
