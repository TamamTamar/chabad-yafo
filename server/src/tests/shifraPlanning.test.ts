        assert.ok(!(await request('/planning?date=' + date)).data.recipes.some((item: Recipe) => item.id === firstRecipe.id));
        const favorite = await request(path + '/favorite', 'POST', { revision: week.revision, name: 'בוקר מוצלח' });
        assert.equal(favorite.status, 200);
        assert.deepEqual(favorite.data.recipes, recipes);
        const generated = week.shopping.filter((item: any) => item.id !== 'legacy');
        const boughtId = generated[0].id;
        const editedId = generated[1].id;
        const removedId = generated[2].id;
        const edited = { ...week, shopping: week.shopping.filter((item: any) => item.id !== removedId).map((item: any) => item.id === boughtId ? { ...item, done: true } : item.id === editedId ? { ...item, quantity: '999' } : item), menu: { recipes: [] } };
